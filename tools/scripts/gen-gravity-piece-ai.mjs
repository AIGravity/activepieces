// [gravity-patch P-005] Generator for the `gravity-piece-ai` custom piece.
//
// WHY: AP runtime-fetches the OFFICIAL `@activepieces/piece-ai` from the
// registry, so the P-004 metering patched into this fork's `ai` piece never
// runs in a deployed AP. To make the metering ship, we publish a renamed copy
// of the `ai` piece (which already carries P-004: `gravity-meter.ts` + the
// OpenRouter case in `ai-sdk.ts`) to public npm as `gravity-piece-ai`, install
// it in AP, and rewrite flows to reference it at clone time.
//
// This script regenerates that copy deterministically from the canonical `ai`
// piece — it is a faithful copy + rename, NOT a fragile source patch, so it
// keeps working across upstream `ai` changes. The auto-publish CI workflow
// (.github/workflows/gravity-piece-ai-autopublish.yml) runs it on every `ai`
// version bump and publishes when the version is new.
//
// Run: node tools/scripts/gen-gravity-piece-ai.mjs   (from repo root)

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SRC = join(ROOT, 'packages', 'pieces', 'community', 'ai')
const OUT_NAME = 'gravity-piece-ai'
const OUT = join(ROOT, 'packages', 'pieces', 'community', OUT_NAME)

// Bump this only when the GRAVITY metering change itself changes WITHOUT an
// upstream `ai` version bump — it forces a new publishable version. Normally
// the published version tracks the `ai` version 1:1.
const GRAVITY_REVISION = 0

function log(msg) { process.stdout.write(`[gen-gravity-piece-ai] ${msg}\n`) }

if (!existsSync(SRC)) {
    throw new Error(`Source ai piece not found at ${SRC}`)
}

const aiPkg = JSON.parse(readFileSync(join(SRC, 'package.json'), 'utf8'))

// Sanity: the canonical ai piece MUST carry the P-004 metering, else the
// generated piece would be a pointless duplicate. Fail loud if it drifted out.
const aiSdk = readFileSync(join(SRC, 'src', 'lib', 'common', 'ai-sdk.ts'), 'utf8')
if (!existsSync(join(SRC, 'src', 'lib', 'common', 'gravity-meter.ts')) || !aiSdk.includes('makeMeteringFetch')) {
    throw new Error('Canonical ai piece is missing the P-004 metering (gravity-meter.ts / makeMeteringFetch). Re-apply P-004 to packages/pieces/community/ai before generating.')
}

const baseVersion = aiPkg.version
const publishVersion = GRAVITY_REVISION === 0 ? baseVersion : `${baseVersion}-g${GRAVITY_REVISION}`

// 1. wipe + recreate output (src is fully regenerated; never hand-edit it)
rmSync(join(OUT, 'src'), { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

// 2. copy the piece source verbatim (includes gravity-meter.ts + patched ai-sdk.ts)
cpSync(join(SRC, 'src'), join(OUT, 'src'), { recursive: true })

// 3. copy depth-relative build configs (same nesting depth → relative paths hold)
for (const f of ['tsconfig.json', 'tsconfig.lib.json', '.eslintrc.json']) {
    if (existsSync(join(SRC, f))) cpSync(join(SRC, f), join(OUT, f))
}

// 4. rewritten package.json — same deps, new public name + version
const outPkg = {
    name: OUT_NAME,
    version: publishVersion,
    type: aiPkg.type ?? 'commonjs',
    main: aiPkg.main ?? './dist/src/index.js',
    types: aiPkg.types ?? './dist/src/index.d.ts',
    dependencies: aiPkg.dependencies,
    scripts: aiPkg.scripts,
    ...(aiPkg.devDependencies ? { devDependencies: aiPkg.devDependencies } : {}),
}
writeFileSync(join(OUT, 'package.json'), JSON.stringify(outPkg, null, 2) + '\n')

// 5. provenance marker + README (so nobody hand-edits the generated tree)
writeFileSync(join(OUT, '.generated-from'), JSON.stringify({
    source: '@activepieces/piece-ai',
    baseVersion,
    publishVersion,
    note: 'AUTO-GENERATED by tools/scripts/gen-gravity-piece-ai.mjs — do not hand-edit; edit the ai piece + re-run.',
}, null, 2) + '\n')
writeFileSync(join(OUT, 'README.md'),
    `# gravity-piece-ai\n\n` +
    `**Auto-generated — do not hand-edit.** A renamed copy of \`@activepieces/piece-ai@${baseVersion}\` ` +
    `carrying the Gravity OpenRouter cost-metering (fork patch P-004). Published to public npm so a ` +
    `runtime-fetch AP can run the metered piece (the official package can't).\n\n` +
    `Regenerate: \`node tools/scripts/gen-gravity-piece-ai.mjs\`. ` +
    `Auto-published by \`.github/workflows/gravity-piece-ai-autopublish.yml\` on each \`ai\` version bump.\n\n` +
    `Flows must reference \`${OUT_NAME}\` instead of \`@activepieces/piece-ai\` — handled by the clone-time ` +
    `piece-name rewrite in core (\`flow-tree.ts\`).\n`)

log(`generated ${OUT_NAME}@${publishVersion} from @activepieces/piece-ai@${baseVersion}`)
// machine-readable last line for CI to parse
process.stdout.write(`PUBLISH_VERSION=${publishVersion}\n`)
